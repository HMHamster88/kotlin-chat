package org.kotlinchat.server.auth

import org.kotlinchat.protocol.KdfParams
import org.kotlinchat.protocol.crypto.Crypto
import org.kotlinchat.protocol.crypto.Scram
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.attribute.PosixFilePermission
import kotlin.io.path.createDirectories

/**
 * What the server persists about the shared password.
 *
 * The password itself is never stored and never transmitted: only the SCRAM verifier
 * (salt + storedKey + serverKey) is written to disk.
 */
class PasswordVerifier(
    val kdf: KdfParams,
    val storedKey: ByteArray,
    val serverKey: ByteArray,
) {
    val salt: ByteArray get() = Crypto.base64Decode(kdf.salt)

    companion object {
        const val DEFAULT_MEMORY_KIB = 65536
        const val DEFAULT_ITERATIONS = 3
        const val DEFAULT_PARALLELISM = 1

        fun create(
            password: String,
            memoryKib: Int = DEFAULT_MEMORY_KIB,
            iterations: Int = DEFAULT_ITERATIONS,
            parallelism: Int = DEFAULT_PARALLELISM,
        ): PasswordVerifier {
            require(password.isNotEmpty()) { "password must not be empty" }
            val kdf = KdfParams(
                salt = Crypto.base64Encode(Crypto.randomBytes(16)),
                m = memoryKib,
                t = iterations,
                p = parallelism,
            )
            val keys = Scram.keys(Scram.deriveAuthKey(password, kdf))
            return PasswordVerifier(kdf = kdf, storedKey = keys.storedKey, serverKey = keys.serverKey)
        }
    }
}

/** `key=value` text file, base64 for binary fields. */
object VerifierFile {

    private const val VERSION = "1"

    fun load(path: Path): PasswordVerifier {
        require(Files.exists(path)) { "verifier file not found: $path (run `init` first)" }
        val values = Files.readAllLines(path)
            .map(String::trim)
            .filter { it.isNotEmpty() && !it.startsWith("#") }
            .mapNotNull { line ->
                val index = line.indexOf('=')
                if (index <= 0) null else line.substring(0, index).trim() to line.substring(index + 1).trim()
            }
            .toMap()

        require(values["version"] == VERSION) { "unsupported verifier version: ${values["version"]}" }
        require(values["alg"] == "argon2id") { "unsupported KDF: ${values["alg"]}" }

        val kdf = KdfParams(
            alg = "argon2id",
            salt = values.getValue("salt"),
            m = values.getValue("m").toInt(),
            t = values.getValue("t").toInt(),
            p = values.getValue("p").toInt(),
        )
        return PasswordVerifier(
            kdf = kdf,
            storedKey = Crypto.base64Decode(values.getValue("storedKey")),
            serverKey = Crypto.base64Decode(values.getValue("serverKey")),
        )
    }

    fun save(path: Path, verifier: PasswordVerifier) {
        path.toAbsolutePath().parent?.createDirectories()
        val body = buildString {
            appendLine("# kotlin-chat password verifier")
            appendLine("# Generated by `kotlin-chat-server init`. Keep this file private.")
            appendLine("version=$VERSION")
            appendLine("alg=argon2id")
            appendLine("salt=${verifier.kdf.salt}")
            appendLine("m=${verifier.kdf.m}")
            appendLine("t=${verifier.kdf.t}")
            appendLine("p=${verifier.kdf.p}")
            appendLine("storedKey=${Crypto.base64Encode(verifier.storedKey)}")
            appendLine("serverKey=${Crypto.base64Encode(verifier.serverKey)}")
        }
        Files.writeString(path, body)
        restrictToOwner(path)
    }

    private fun restrictToOwner(path: Path) {
        runCatching {
            Files.setPosixFilePermissions(
                path,
                setOf(PosixFilePermission.OWNER_READ, PosixFilePermission.OWNER_WRITE),
            )
        } // Windows has no POSIX permissions; ACLs are the operator's responsibility.
    }
}
